<?php

namespace Database\Seeders;

use App\Models\Post;
use App\Models\PostCategory;
use App\Models\Product;
use Illuminate\Database\Seeder;

class BlogSeeder extends Seeder
{
    public function run(): void
    {
        $guides = PostCategory::updateOrCreate(['slug' => 'buying-guide'], [
            'name'        => 'راهنمای خرید',
            'description' => 'راهنماهای انتخاب و مقایسه آیفون تصویری و تجهیزات برق ساختمان.',
            'seo_title'   => 'راهنمای خرید آیفون تصویری | بلاگ برقی‌شاپ',
        ]);

        $tech = PostCategory::updateOrCreate(['slug' => 'installation'], [
            'name'        => 'نصب و عیب‌یابی',
            'description' => 'آموزش نصب، سیم‌کشی و رفع مشکلات رایج آیفون تصویری.',
        ]);

        $posts = [
            [
                'title'   => 'راهنمای کامل خرید آیفون تصویری سیماران در سال ۱۴۰۵',
                'cat'     => $guides,
                'excerpt' => 'از انتخاب اندازه نمایشگر تا تفاوت مدل‌های حافظه‌دار و معمولی؛ هر آنچه پیش از خرید آیفون تصویری باید بدانید.',
                'faq'     => [
                    ['q' => 'تفاوت آیفون تصویری حافظه‌دار با معمولی چیست؟',
                     'a' => 'مدل حافظه‌دار تصویر مراجعین را در زمان عدم حضور شما ذخیره می‌کند تا بعداً قابل مشاهده باشد؛ مدل معمولی این قابلیت را ندارد.'],
                    ['q' => 'چه اندازه نمایشگری مناسب واحد مسکونی است؟',
                     'a' => 'برای واحدهای مسکونی معمولی نمایشگر ۴.۳ تا ۷ اینچ کافی است. نمایشگرهای ۱۰ اینچ بیشتر برای ویلا و واحدهای لوکس انتخاب می‌شوند.'],
                ],
            ],
            [
                'title'   => 'آیفون تصویری با گوشی یا بدون گوشی؟ مقایسه کامل',
                'cat'     => $guides,
                'excerpt' => 'مزایا و معایب مدل‌های هندزفری در برابر مدل‌های دارای گوشی، از نظر کیفیت صدا، دوام و قیمت.',
            ],
            [
                'title'   => 'آموزش سیم‌کشی و نصب آیفون تصویری قدم به قدم',
                'cat'     => $tech,
                'excerpt' => 'راهنمای تصویری اتصال پنل، مانیتور، قفل برقی و منبع تغذیه به همراه نکات ایمنی.',
            ],
            [
                'title'   => 'چرا آیفون تصویری تصویر نمی‌دهد؟ ۷ علت رایج و راه‌حل',
                'cat'     => $tech,
                'excerpt' => 'از قطعی تغذیه و اتصال سست کابل تا خرابی دوربین پنل؛ عیب‌یابی گام‌به‌گام بدون نیاز به تعویض دستگاه.',
            ],
            [
                'title'   => 'خرید عمده تجهیزات سیماران برای پروژه‌های ساختمانی',
                'cat'     => $guides,
                'excerpt' => 'شرایط همکاری، قیمت‌گذاری پلکانی و نحوه ثبت‌نام به‌عنوان همکار در برقی‌شاپ.',
            ],
        ];

        foreach ($posts as $i => $data) {
            $post = Post::updateOrCreate(['title' => $data['title']], [
                'post_category_id' => $data['cat']->id,
                'excerpt'          => $data['excerpt'],
                'body'             => $this->body($data['title'], $data['excerpt']),
                'status'           => 'published',
                'published_at'     => now()->subDays(20 - $i * 3),
                'faq'              => $data['faq'] ?? null,
                'seo_title'        => $data['title'].' | برقی‌شاپ',
                'seo_description'  => mb_substr($data['excerpt'], 0, 150),
            ]);

            $post->products()->sync(
                Product::query()->inRandomOrder()->limit(3)->pluck('id')
            );
        }
    }

    protected function body(string $title, string $excerpt): string
    {
        return <<<HTML
        <p>$excerpt</p>
        <h2>مقدمه</h2>
        <p>انتخاب درست تجهیزات برق ساختمان، هم در هزینه بلندمدت و هم در آسایش روزمره ساکنان اثر مستقیم دارد. در این مقاله موضوع «{$title}» را به زبان ساده بررسی می‌کنیم.</p>
        <h2>نکات کلیدی</h2>
        <ul>
            <li>پیش از خرید، نیاز واقعی ساختمان را مشخص کنید؛ گران‌ترین گزینه لزوماً مناسب‌ترین نیست.</li>
            <li>گارانتی و در دسترس بودن خدمات پس از فروش را جدی بگیرید.</li>
            <li>سازگاری قطعات با یکدیگر را پیش از سفارش بررسی کنید.</li>
        </ul>
        <h2>جمع‌بندی</h2>
        <p>اگر در انتخاب مدل مناسب تردید دارید، کارشناسان برقی‌شاپ به‌صورت رایگان شما را راهنمایی می‌کنند.</p>
        HTML;
    }
}
